export const cuts = photoCatalog;

export function filterCuts(audience = 'all', style = 'all') {
  return cuts.filter(cut => (audience === 'all' || cut.audience === audience) && (style === 'all' || cut.style === style));
}
export function validLanguage(value) { return value === 'en' ? 'en' : 'es'; }
export function toggleLike(likes, id) {
  const updated = new Set(likes);
  if (updated.has(id)) updated.delete(id); else updated.add(id);
  return updated;
}
